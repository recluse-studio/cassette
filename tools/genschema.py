# genschema.py — emits schema/ contracts, validator, and manifest from the ledger's shapes (Q6/Q9/Q31/Q50/Q57); depends on errors.py.
"""Generate the machine contracts. schema/ is data plus one generated validator; never hand-edit.

Shapes come from the research ledger: Error and Request/Operation (Q6), RunEvent (Q31),
SourceDescriptor (Q9), RemoteMetadata field records (Q50), and the cartridge Root manifest (Q57).
Every emitted file is recorded by digest in schema/MANIFEST.json; tools/ledger.py fails closed on
any drift. Regeneration is deterministic: same inputs, same bytes.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import errors

GENERATED_NOTE = "GENERATED by tools/genschema.py — do not edit"

