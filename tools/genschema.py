def emit(outdir: Path) -> dict[str, str]:
    """Write every generated file and return its name-to-SHA-256 integrity map."""
    certificate_dimensions = load_certificate_dimensions()
    verify_certificate_dimensions(certificate_dimensions)
    outdir.mkdir(parents=True, exist_ok=True)
    written: dict[str, str] = {}

    def put(name: str, content: str) -> None:
        (outdir / name).write_text(content, encoding="utf-8")
        written[name] = hashlib.sha256(content.encode("utf-8")).hexdigest()

    for kind, schema in sorted(CONTRACTS.items()):
        document = {"$id": f"{SCHEMA_BASE}/{kind}.json", **schema}
        put(f"{kind}.json", json.dumps(document, ensure_ascii=False, indent=2, sort_keys=True) + "\n")
    tables = (
        f"# tables.py — {GENERATED_NOTE}; depends on (none).\n"
        f"MLX_RUNTIME = {pprint.pformat(MLX_RUNTIME, sort_dicts=True, width=100)}\n"
        f"DISPATCH_DIGEST = {DISPATCH_DIGEST!r}\n"
        f"OPERATOR_DISPATCH = {pprint.pformat(OPERATOR_DISPATCH_RECORD, sort_dicts=True, width=100)}\n"
        f"DISPATCH_ROWS = {pprint.pformat(DISPATCH_ROWS, sort_dicts=True, width=100)}\n"
        f"Q40_MODES = {pprint.pformat(Q40_MODES, sort_dicts=True, width=100)}\n"
        f"Q77_FIELDS = {pprint.pformat(Q77_FIELDS, sort_dicts=True, width=100)}\n"
        f"Q76_FIELD_STATUSES = {pprint.pformat(Q76_FIELD_STATUSES, sort_dicts=True, width=100)}\n"
        f"ADAPTER_EVENT_FORMATS = {pprint.pformat(ADAPTER_EVENT_FORMATS, sort_dicts=True, width=100)}\n"
        f"ADAPTER_PROTOCOLS = {pprint.pformat(ADAPTER_PROTOCOLS, sort_dicts=True, width=100)}\n"
        f"HARDWARE_PLAN_VERSION = {HARDWARE_PLAN_VERSION!r}\n"
        f"HARDWARE_PLAN_CATALOG_VERSION = {HARDWARE_PLAN_CATALOG_VERSION!r}\n"
        f"CERTIFICATE_DIMENSIONS = {pprint.pformat(certificate_dimensions, sort_dicts=True, width=100)}\n"
    )
    put("tables.py", tables)
    put("validator.py", VALIDATOR_SRC.format(note=GENERATED_NOTE))
    (outdir / "MANIFEST.json").write_text(
        json.dumps(written, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return written


def main() -> int:
    outdir = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "schema"
    emit(outdir)
    return 0


