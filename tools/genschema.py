def text(*, enum: list[str] | None = None, empty: bool = False) -> dict:
    shape: dict = {"type": "string"}
    if not empty:
        shape["minLength"] = 1
    if enum is not None:
        shape["enum"] = enum
    return shape


def array(items: dict | None = None, *, minimum: int | None = None) -> dict:
    shape: dict = {"type": "array"}
    if items is not None:
        shape["items"] = items
    if minimum is not None:
        shape["minItems"] = minimum
    return shape


def ref(kind: str) -> dict:
    return {"$ref": f"{kind}.json"}


def record(
    title: str,
    question: str,
    properties: dict[str, dict],
    *,
    optional: tuple[str, ...] = (),
) -> dict:
    return {
        "$schema": SCHEMA_DIALECT,
        "$comment": f"{GENERATED_NOTE}; authority: {question}",
        "title": title,
        "type": "object",
        "additionalProperties": False,
        "properties": properties,
        "required": sorted(set(properties) - set(optional)),
    }


