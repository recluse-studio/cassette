"""Generate Cassette's machine contracts. Files under schema/ are never hand-edited.

The emitted documents are JSON Schema Draft 2020-12 contracts. The generated validator executes
the small schema subset used here without adding a runtime dependency. MANIFEST.json binds every
generated byte; tools/ledger.py also regenerates the directory so editing a schema and its digest
together still fails.
"""

